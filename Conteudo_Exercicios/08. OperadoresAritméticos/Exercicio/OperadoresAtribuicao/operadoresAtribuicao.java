package OperadoresAtribuicao;

public class operadoresAtribuicao {
    public static void main(String[] args) {

        System.out.println("=== ADIÇÃO ===");
        double UmNumero = 5.0;
        UmNumero += 2.0;
        System.out.println("A adição de 5 e 2 é "+UmNumero);
        // ------------------------------------------------------------------
        System.out.println("=== SUBTRAÇÃO ===");
        UmNumero = 5.0;
        UmNumero -= 2.0;
        System.out.println("A subtração de 5 e 2 é " +UmNumero);
        // ------------------------------------------------------------------
        System.out.println("=== Multiplicação ===");
        UmNumero = 5.0;
        UmNumero *= 2.0;
        System.out.println("A multiplacação de 5 e 2 é " +UmNumero);
        // ------------------------------------------------------------------
        System.out.println("=== DIVISÃO ===");
        UmNumero = 5.0;
        UmNumero /= 2.0;
        System.out.println("A divisão de 5 e 2 é " +UmNumero);
        // ------------------------------------------------------------------
        System.out.println("Modulo ou Resto");
        UmNumero = 5.0;
        UmNumero %= 2.0;
        System.out.println("O módulo ou o resto de 5 e 2 é " +UmNumero);

    }
}
