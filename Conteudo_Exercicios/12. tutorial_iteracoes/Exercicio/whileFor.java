public class whileFor {
    public static void main(String[] args) {
        int contador =0;
        // informando que o contador é igual a zero 
        while (contador < 5) {
            // enquanto o valor do contador for menor que 5, ele vai ficar contando
            // A partir do momento que não for mais menor que 5 ele para de contar 
            System.out.println(contador);
            contador = contador +1;
        }
    }
}
